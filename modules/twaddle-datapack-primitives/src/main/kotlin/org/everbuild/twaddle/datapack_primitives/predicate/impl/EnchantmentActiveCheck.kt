package org.everbuild.twaddle.datapack_primitives.predicate.impl

import net.minestom.server.codec.Codec
import net.minestom.server.codec.StructCodec
import org.everbuild.twaddle.datapack_primitives.context.DataContext
import org.everbuild.twaddle.datapack_primitives.context.EnchantmentActiveContext
import org.everbuild.twaddle.datapack_primitives.number_provider.NumberProviderDeclaration
import org.everbuild.twaddle.datapack_primitives.predicate.ContextPredicate
import org.everbuild.twaddle.datapack_primitives.predicate.ContextPredicateKeys
import org.everbuild.twaddle.datapack_primitives.predicate.ContextPredicateType
import java.util.Random

private data class EnchantmentActiveCheckPredicate(val active: Boolean) : ContextPredicate {
    override fun type() = ContextPredicateKeys.ENCHANTMENT_ACTIVE_CHECK
    override fun test(context: DataContext, random: Random) = context[EnchantmentActiveContext] == active
}

internal class EnchantmentActiveCheckPredicateType : ContextPredicateType {
    override fun codec(
        predicateCodec: Codec<ContextPredicate>,
        intProviderCodec: Codec<NumberProviderDeclaration<Int>>,
        floatProviderCodec: Codec<NumberProviderDeclaration<Float>>,
    ): StructCodec<out ContextPredicate> = StructCodec.struct(
        "active", Codec.BOOLEAN, EnchantmentActiveCheckPredicate::active,
        ::EnchantmentActiveCheckPredicate,
    ).asContextPredicateCodec()
}
